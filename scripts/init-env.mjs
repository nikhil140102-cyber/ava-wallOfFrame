// Creates .env.local with a random SESSION_SECRET the first time you run `npm run setup`.
import fs from "node:fs";
import crypto from "node:crypto";

if (fs.existsSync(".env.local")) {
  console.log(".env.local already exists — leaving it alone.");
} else {
  const secret = crypto.randomBytes(32).toString("base64url");
  fs.writeFileSync(
    ".env.local",
    `# Generated by npm run setup. Keep this file private.\nSESSION_SECRET=${secret}\nDATABASE_URL=file:./data/app.db\n# Show the one-tap demo accounts on the sign-in page even in production builds:\nSHOW_DEMO_ACCOUNTS=true\n`
  );
  console.log("Created .env.local with a new SESSION_SECRET.");
}
fs.mkdirSync("data", { recursive: true });
